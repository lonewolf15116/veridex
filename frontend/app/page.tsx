function emptyRow(): NumberRow {
  return { label: "", value: "", evidence: "estimate" };
}

function defaultAnswer(): AnswerState {
  return { skipped: false, text: "", numbers: [emptyRow()] };
}

function hasContent(q: Question, a: AnswerState): boolean {
  if (a.skipped) return false;
  return q.kind === "numbers"
    ? a.numbers.some(r => r.label.trim().length > 0)
    : a.text.trim().length > 0;
}

function answerExcerpt(q: Question, a: AnswerState): string {
  const raw = q.kind === "numbers"
    ? a.numbers
        .filter(r => r.label.trim())
        .map(r => `${r.label.trim()}${r.value.trim() ? `: ${r.value.trim()}` : ""} (${EVIDENCE_LABEL[r.evidence].toLowerCase()})`)
        .join("; ")
    : a.text.trim();
  return raw.length > 160 ? `${raw.slice(0, 157)}…` : raw;
}

