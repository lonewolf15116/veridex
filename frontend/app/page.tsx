function critiqueToPlainText(
  lensStates: Record<LensId, LensState>,
  lenses: typeof LENSES,
  extras?: ExportExtras
): string {
  const lines: string[] = [extras ? "VERIDEX REFINED CRITIQUE" : "VERIDEX CRITIQUE", "═".repeat(60), ""];
  for (const lens of lenses) {
    const state = lensStates[lens.id];
    if (state.status !== "done") continue;
    const r = state.result;
    lines.push(`${lens.tag} · ${lens.label.toUpperCase()}`);
    lines.push("─".repeat(40));
    lines.push(r.summary);
    lines.push("");
    for (const flaw of r.flaws) {
      lines.push(`[${flaw.severity.toUpperCase()}] ${flaw.title}`);
      lines.push(flaw.description);
      lines.push(`→ ${flaw.question}`);
      lines.push("");
    }
    lines.push("");
  }
  if (extras) {
    lines.push("GAPS YOU FILLED", "─".repeat(40), GAPS_NOTE, "");
    for (const t of extras.answered) lines.push(`• ${t}`);
    if (extras.skipped.length > 0) {
      lines.push("", "Skipped:");
      for (const t of extras.skipped) lines.push(`• ${t}`);
    }
    lines.push("", "");
  }
  lines.push(`Generated by Veridex · veridex.fyi`);
  return lines.join("\n");
}

function critiqueToMarkdown(
  lensStates: Record<LensId, LensState>,
  lenses: typeof LENSES,
  extras?: ExportExtras
): string {
  const lines: string[] = [extras ? "# Veridex Refined Critique" : "# Veridex Critique", ""];
  for (const lens of lenses) {
    const state = lensStates[lens.id];
    if (state.status !== "done") continue;
    const r = state.result;
    lines.push(`## ${lens.label}`);
    lines.push(`> ${r.summary}`);
    lines.push("");
    for (const flaw of r.flaws) {
      lines.push(`### \`${flaw.severity.toUpperCase()}\` ${flaw.title}`);
      lines.push(flaw.description);
      lines.push("");
      lines.push(`**Key question:** ${flaw.question}`);
      lines.push("");
    }
  }
  if (extras) {
    lines.push("## Gaps you filled");
    lines.push(`> ${GAPS_NOTE}`);
    lines.push("");
    for (const t of extras.answered) lines.push(`- ${t}`);
    if (extras.skipped.length > 0) {
      lines.push("", "**Skipped**", "");
      for (const t of extras.skipped) lines.push(`- ${t}`);
    }
    lines.push("");
  }
  lines.push("---");
  lines.push("*Generated by [Veridex](https://veridex.fyi)*");
  return lines.join("\n");
}

