function CritiqueProduct() {
  const [doc, setDoc] = useState("");
  const [mode, setMode]   = useState<Mode>("plan");
  const [stage, setStage] = useState<Stage>("idea");
  const [lensStates, setLensStates] = useState<Record<LensId, LensState>>(idleStates);
  const [running, setRunning]     = useState(false);
  const [done, setDone]           = useState(false);
  const [requestError, setRequestError] = useState<string | null>(null);
  const [errorTitle, setErrorTitle]     = useState("Critique not started");
  const abortRef                  = useRef<AbortController | null>(null);

  // Idea Builder state
  const [ideaRun, setIdeaRun]           = useState<{ doc: string; stage: Stage } | null>(null);
  const [questions, setQuestions]       = useState<Question[]>([]);
  const [refineToken, setRefineToken]   = useState<string | null>(null);
  const [answers, setAnswers]           = useState<Record<string, AnswerState>>({});
  const [refinePhase, setRefinePhase]   = useState<RefinePhase>("none");
  const [refinedStates, setRefinedStates] = useState<Record<LensId, LensState>>(idleStates);
  const [refinement, setRefinement]     = useState<SsePayload["refinement"] | null>(null);
  const [gapsRecord, setGapsRecord]     = useState<GapsRecord | null>(null);
  const [showFirst, setShowFirst]       = useState(true);

  function updateLens(id: LensId, state: LensState) {
    setLensStates(prev => ({ ...prev, [id]: state }));
  }
  function updateRefined(id: LensId, state: LensState) {
    setRefinedStates(prev => ({ ...prev, [id]: state }));
  }

  async function runCritique() {
    if (!doc.trim() || doc.trim().length < 20 || running || refinePhase === "running") return;

    setRunning(true);
    setDone(false);
    setRequestError(null);
    setErrorTitle("Critique not started");
    for (const l of LENSES) updateLens(l.id, { status: "idle" });

    // Clear any previous refinement / questions
    setQuestions([]);
    setRefineToken(null);
    setAnswers({});
    setRefinePhase("none");
    setRefinedStates(idleStates());
    setRefinement(null);
    setGapsRecord(null);
    setShowFirst(true);

    const isIdea = mode === "idea";
    setIdeaRun(isIdea ? { doc, stage } : null);
    const body = isIdea ? { strategy_doc: doc, stage } : { strategy_doc: doc };

    const abort = new AbortController();
    abortRef.current = abort;

    const { error } = await streamCritique(body, abort.signal, (event, payload) => {
      if      (event === "pass_started")   updateLens(payload.lens as LensId, { status: "running" });
      else if (event === "pass_completed") updateLens(payload.lens as LensId, { status: "done", result: payload.result as CriticPassResult });
      else if (event === "error")          updateLens(payload.lens as LensId, { status: "error", reason: payload.reason ?? "" });
      else if (event === "done") {
        setDone(true);
        if (isIdea) {
          setQuestions(Array.isArray(payload.questions) ? payload.questions : []);
          setRefineToken(typeof payload.refine_token === "string" ? payload.refine_token : null);
        }
      }
    });
    if (error) setRequestError(error);
    setRunning(false);
  }

  function setAnswer(gap: string, next: AnswerState) {
    setAnswers(prev => ({ ...prev, [gap]: next }));
  }

  const answerFor = (q: Question) => answers[q.gap] ?? defaultAnswer();
  const canRefine = questions.some(q => hasContent(q, answerFor(q)));

  async function runRefine() {
    if (!ideaRun || !refineToken || running || refinePhase !== "none" || !canRefine) return;

    const payloadAnswers: object[] = [];
    const record: GapsRecord = { answered: [], skipped: [] };
    for (const q of questions) {
      const a = answerFor(q);
      if (a.skipped) {
        payloadAnswers.push({ gap: q.gap, skipped: true });
        record.skipped.push(q);
      } else if (hasContent(q, a)) {
        payloadAnswers.push({
          gap: q.gap,
          skipped: false,
          text: q.kind === "text" ? a.text.trim() : "",
          numbers: q.kind === "numbers"
            ? a.numbers
                .filter(r => r.label.trim())
                .map(r => ({ label: r.label.trim(), value: r.value.trim(), evidence: r.evidence }))
            : [],
        });
        record.answered.push({ question: q, excerpt: answerExcerpt(q, a) });
      }
    }
    if (record.answered.length === 0) return;

    setRequestError(null);
    setErrorTitle("Refinement not started");
    setRefinedStates(idleStates());
    setRefinement(null);
    setGapsRecord(record);
    setShowFirst(false);
    setRefinePhase("running");

    const abort = new AbortController();
    abortRef.current = abort;

    let started = false;
    const { error, status } = await streamCritique(
      {
        strategy_doc: ideaRun.doc,
        stage: ideaRun.stage,
        refine: { token: refineToken, answers: payloadAnswers },
      },
      abort.signal,
      (event, payload) => {
        if (event === "pass_started") {
          started = true;
          updateRefined(payload.lens as LensId, { status: "running" });
        }
        else if (event === "pass_completed") updateRefined(payload.lens as LensId, { status: "done", result: payload.result as CriticPassResult });
        else if (event === "error")          updateRefined(payload.lens as LensId, { status: "error", reason: payload.reason ?? "" });
        else if (event === "done")           setRefinement(payload.refinement ?? null);
      },
    );

    if (error) {
      setRequestError(error);
      if (started) {
        setRefinePhase("done");
      } else {
        // Nothing streamed: restore the first critique. A 409 means the refinement is gone for good.
        setRefinePhase(status === 409 ? "spent" : "none");
        setGapsRecord(null);
        setShowFirst(true);
      }
    } else {
      setRefinePhase("done");
    }
  }

  const anyResults      = LENSES.some(l => lensStates[l.id].status !== "idle");
  const completedCount  = LENSES.filter(l => ["done","error"].includes(lensStates[l.id].status)).length;

  const refinedActive    = LENSES.filter(l => refinedStates[l.id].status !== "idle");
  const refinedCompleted = refinedActive.filter(l => ["done","error"].includes(refinedStates[l.id].status)).length;
  const refinedTotal     = refinement?.lenses?.length ?? refinedActive.length;
  const refinedIds       = refinement?.lenses ?? refinedActive.map(l => l.id as string);
  const notRerun         = LENSES.filter(l => !refinedIds.includes(l.id));
  const showRefined      = (refinePhase === "running" || refinePhase === "done") && gapsRecord !== null;
  const refinedExportable = refinePhase === "done" && refinedCompleted > 0 && gapsRecord !== null;

  const firstCritique = (
    <>
      {/* Progress bar */}
      {anyResults && (
        <div className="space-y-2">
          <div className="flex items-center justify-between">
            <Tag>{running ? "Running five lenses in parallel" : done ? "Critique complete" : "Finishing…"}</Tag>
            <p className="text-[11px] text-white/25 font-mono">{completedCount}&nbsp;/&nbsp;{LENSES.length}</p>
          </div>
          <div className="h-px w-full bg-white/[0.06] rounded-full overflow-hidden">
            <div
              className="h-px bg-white/40 rounded-full transition-all duration-500 ease-out"
              style={{ width: `${(completedCount / LENSES.length) * 100}%` }}
            />
          </div>
        </div>
      )}

      {/* Lens panels */}
      {anyResults && (
        <div className="space-y-3">
          {LENSES.map(lens => (
            <LensPanel key={lens.id} lens={lens} state={lensStates[lens.id]} />
          ))}
        </div>
      )}
    </>
  );

  return (
    <section id="product" className="py-20">
      <div className="mx-auto max-w-3xl px-6 space-y-8">
        {/* Section header */}
        <div>
          <Tag>Run a critique</Tag>
          <h2 className="mt-3 text-[28px] sm:text-[32px] font-semibold leading-tight tracking-[-0.02em] text-white">
            Paste your strategy. Get five critics.
          </h2>
        </div>

        {/* Input card */}
        <div className="rounded-2xl border border-white/10 bg-[#111] overflow-hidden">
          {/* Mode switch */}
          <div className="px-6 pt-5">
            <div role="group" aria-label="Input mode" className="inline-flex rounded-xl border border-white/10 bg-white/[0.03] p-1">
              {([["plan", "I have a plan"], ["idea", "I only have an idea"]] as [Mode, string][]).map(([m, label]) => (
                <button
                  key={m}
                  type="button"
                  aria-pressed={mode === m}
                  onClick={() => setMode(m)}
                  className={`rounded-lg px-4 py-1.5 text-[12px] font-semibold transition-all ${
                    mode === m ? "bg-white text-black" : "text-white/45 hover:text-white/75"
                  }`}
                >
                  {label}
                </button>
              ))}
            </div>
          </div>
          <div className="px-6 pt-5 pb-4 border-b border-white/[0.06]">
            {mode === "plan" ? (
              <>
                <p className="text-[10px] font-bold uppercase tracking-[0.16em] text-white/30 mb-1">Strategy Document</p>
                <p className="text-[14px] font-semibold text-white/80">Describe what you&apos;re building</p>
                <p className="text-[11px] text-white/25 mt-0.5">Include: product, audience, pricing, growth strategy, and what makes it defensible.</p>
              </>
            ) : (
              <>
                <p className="text-[10px] font-bold uppercase tracking-[0.16em] text-white/30 mb-1">Your Idea</p>
                <p className="text-[14px] font-semibold text-white/80">Describe your idea in a few sentences</p>
                <p className="text-[11px] text-white/25 mt-0.5">Say who it is for, what it does, and anything you already know. Rough is fine.</p>
              </>
            )}
          </div>
          <div className="px-6 py-5">
            <textarea
              value={doc}
              onChange={e => setDoc(e.target.value.slice(0, 10000))}
              maxLength={10000}
              placeholder={mode === "plan"
                ? "Example:\n\nWe're building a $20/month AI tool that critiques startup strategy docs. Target: solo founders. Launch in 4 weeks. Growth via founder Twitter. Defensibility: proprietary critique framework."
                : "Example:\n\nAn app that helps small restaurants cut food waste by predicting what they will sell tomorrow. I think owners would pay a monthly fee, but I have not talked to any yet."}
              className="w-full h-40 resize-none bg-transparent text-[13px] text-white/80 placeholder-white/15 outline-none leading-relaxed"
            />
          </div>
          {mode === "idea" && (
            <div className="px-6 pb-5 space-y-2">
              <Tag>Where are you?</Tag>
              <div role="group" aria-label="Stage" className="flex flex-wrap gap-2">
                {STAGES.map(s => (
                  <button
                    key={s.id}
                    type="button"
                    aria-pressed={stage === s.id}
                    onClick={() => setStage(s.id)}
                    className={`rounded-full border px-3.5 py-1.5 text-[12px] font-semibold transition-all ${
                      stage === s.id
                        ? "border-white/30 bg-white/10 text-white/90"
                        : "border-white/10 text-white/40 hover:text-white/70 hover:border-white/20"
                    }`}
                  >
                    {s.label}
                  </button>
                ))}
              </div>
            </div>
          )}
          <div className="flex items-center justify-between px-6 py-4 border-t border-white/[0.06] bg-white/[0.015]">
            <span className="text-[11px] text-white/20 font-mono">
              {doc.length > 0 ? `${doc.length.toLocaleString()} / 10,000 chars` : "min. 20 chars"}
            </span>
            <button
              onClick={runCritique}
              disabled={running || refinePhase === "running" || doc.trim().length < 20}
              className="flex items-center gap-2 rounded-xl bg-white px-5 py-2.5 text-[13px] font-semibold text-black transition-all disabled:opacity-25 hover:opacity-90 active:scale-[0.98]"
            >
              {running
                ? <><span className="w-1.5 h-1.5 rounded-full bg-black/40 animate-pulse" />Analyzing…</>
                : "Run critique"}
            </button>
          </div>
        </div>

        {/* Request-level error (rate limit, validation, server down) */}
        {requestError && (
          <div role="alert" className="rounded-2xl border border-amber-400/25 bg-amber-400/[0.06] px-5 py-4">
            <p className="text-[13px] font-semibold text-amber-200/90">{errorTitle}</p>
            <p className="mt-1 text-[12px] text-amber-100/60 leading-relaxed">{requestError}</p>
          </div>
        )}

        {/* Refined critique (above the first critique) */}
        {showRefined && gapsRecord && (
          <div className="space-y-4">
            <h3 className="text-[20px] font-semibold tracking-[-0.01em] text-white">Refined critique</h3>
            <div className="space-y-2">
              <div className="flex items-center justify-between">
                <Tag>{refinePhase === "running" ? "Re-running the lenses your answers affect" : "Refinement complete"}</Tag>
                <p className="text-[11px] text-white/25 font-mono">{refinedCompleted}&nbsp;/&nbsp;{refinedTotal}</p>
              </div>
              <div className="h-px w-full bg-white/[0.06] rounded-full overflow-hidden">
                <div
                  className="h-px bg-white/40 rounded-full transition-all duration-500 ease-out"
                  style={{ width: `${refinedTotal > 0 ? (refinedCompleted / refinedTotal) * 100 : 0}%` }}
                />
              </div>
            </div>
            {refinedActive.length > 0 && (
              <div className="space-y-3">
                {refinedActive.map(lens => (
                  <LensPanel key={lens.id} lens={lens} state={refinedStates[lens.id]} />
                ))}
              </div>
            )}
            {refinePhase === "done" && notRerun.length > 0 && (
              <p className="text-[11px] text-white/30 leading-relaxed">
                {`Not re-run (your answers don't affect them): ${notRerun.map(l => l.label).join(", ")}. Their first-critique results below still stand.`}
              </p>
            )}
            <GapsFilledBox record={gapsRecord} />
          </div>
        )}

        {/* First critique: plain layout unless a refinement exists */}
        {showRefined ? (
          anyResults && (
            <div className="space-y-4">
              <div className="flex items-center justify-between">
                <h3 className="text-[20px] font-semibold tracking-[-0.01em] text-white/80">First critique</h3>
                <button
                  type="button"
                  aria-expanded={showFirst}
                  onClick={() => setShowFirst(s => !s)}
                  className="rounded-xl border border-white/10 bg-white/[0.04] px-4 py-2 text-[12px] font-semibold text-white/60 transition-all hover:bg-white/[0.07] hover:text-white"
                >
                  {showFirst ? "Hide first critique" : "Show first critique"}
                </button>
              </div>
              {showFirst && <div className="space-y-8">{firstCritique}</div>}
            </div>
          )
        ) : (
          firstCritique
        )}

        {/* Sharpen panel / free refinement used */}
        {ideaRun && done && questions.length > 0 && refinePhase === "none" && (
          <SharpenPanel
            questions={questions}
            answers={answers}
            onChange={setAnswer}
            canSubmit={canRefine && refineToken !== null}
            busy={running}
            onSubmit={runRefine}
          />
        )}
        {ideaRun && refinePhase !== "none" && (
          <div className="rounded-2xl border border-white/[0.06] bg-[#0f0f0f] px-6 py-4">
            <p className="text-[12px] text-white/45 leading-relaxed">
              {"You've used this critique's free refinement. Start a new critique to refine again."}
            </p>
          </div>
        )}

        {/* Export actions: the refined critique when one exists, otherwise the first */}
        {refinedExportable && gapsRecord ? (
          <ExportBar
            lensStates={refinedStates}
            extras={{
              answered: gapsRecord.answered.map(a => a.question.text),
              skipped: gapsRecord.skipped.map(q => q.text),
            }}
          />
        ) : (
          done && completedCount > 0 && refinePhase !== "running" && (
            <ExportBar lensStates={lensStates} />
          )
        )}
      </div>
    </section>
  );
}

